#: Each form -> its Polish form.
GIVEN: dict[str, str] = {
    form: polish
    for line in _GROUPS
    for polish, forms in [line.split(": ")]
    for form in (polish, *forms.split())
}


def given(words: frozenset[str]) -> frozenset[str]:
    """Folded name words with every first name in its Polish form."""
    return frozenset(GIVEN.get(w, w) for w in words)
